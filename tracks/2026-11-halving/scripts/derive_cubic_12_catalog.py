#!/usr/bin/env python3
"""Independently regenerate the 85 connected cubic order-12 representatives.

Generation: insert a new edge between two distinct subdivided edges of each
order-10 cubic graph (84 classes), then perform one specified valid 2-switch
(85th class). Pairwise distinctness uses exact adjacency walk-count vectors
as invariants, plus VF2 when a signature collides. The published count of 85
classes is used to infer completeness, NOT proven from this generator alone.
"""
from __future__ import annotations
from collections import defaultdict
from itertools import combinations
from pathlib import Path
import json

import networkx as nx
import numpy as np
from census_small_bases import read_catalog


def walk_signature(G):
    """Exact traces of adjacency powers 3 through 9 (integer arithmetic)."""
    A=nx.to_numpy_array(G,dtype=np.int64)
    P=A.copy()
    traces=[]
    for exponent in range(1,10):
        P=P@A
        if exponent>=3:
            traces.append(int(P.trace()))
    return tuple(traces)


def generate():
    groups=defaultdict(list)
    for B in read_catalog()[10]:
        for ((a,b),(c,d)) in combinations(B.edges(),2):
            G=B.copy()
            G.remove_edges_from(((a,b),(c,d)))
            G.add_edges_from(((10,a),(10,b),(11,c),(11,d),(10,11)))
            sig=walk_signature(G)
            if not any(nx.is_isomorphic(G,H) for H in groups[sig]):
                groups[sig].append(G)
    reps=[G for group in groups.values() for G in group]
    assert len(reps)==84
    # Distinct class not generated by this two-edge insertion operation.
    H=reps[0].copy()
    assert H.has_edge(3,10) and H.has_edge(7,8)
    assert not H.has_edge(3,8) and not H.has_edge(10,7)
    H.remove_edges_from(((3,10),(7,8)))
    H.add_edges_from(((3,8),(10,7)))
    assert nx.is_connected(H) and all(d==3 for _,d in H.degree())
    assert not any(nx.is_isomorphic(H,J) for J in groups[walk_signature(H)])
    groups[walk_signature(H)].append(H)
    reps=[G for group in groups.values() for G in group]
    assert len(reps)==85
    return reps


if __name__=='__main__':
    reps=generate()
    here=Path(__file__).resolve().parent
    saved=[nx.from_graph6_bytes(s.encode()) for s in json.loads((here/'cubic_catalog_n12.json').read_text())]
    assert {walk_signature(G) for G in reps}=={walk_signature(G) for G in saved}
    print('Regenerated 85 pairwise nonisomorphic cubic graphs of order 12; fixture matches.')
